/**
 * Item registry.
 *
 * Everything a player can hold, craft, eat, drink, wear or sell lives here.
 * An item's *kind* decides what the game does with it — a tool mines, a weapon
 * damages, armour absorbs, food restores, a potion applies an effect — and the
 * numeric fields are the balance sheet the rest of the game reads from.
 *
 * Deliberately hand-written rather than generated: a sword should feel like a
 * sword, and a "Wooden Sword" that does 4 damage with 59 durability is a
 * promise the player can hold in their head.
 */

export type ItemKind =
  | 'tool' | 'weapon' | 'armor' | 'food' | 'material'
  | 'potion' | 'magic' | 'quest' | 'misc';

export interface ItemDef {
  id: number;
  name: string;
  kind: ItemKind;
  /** Max stack size. 1 for tools, weapons and armour. */
  stack: number;
  /** Base damage for weapons, or harvest bonus for tools. */
  damage?: number;
  /** Tool harvest tier (0 = hand). */
  harvest?: number;
  /** Durability in uses. */
  durability?: number;
  /** Armour points. */
  armor?: number;
  /** Armour toughness (reduces damage taken past armour points). */
  toughness?: number;
  /** Knockback multiplier. */
  knockback?: number;
  /** Attack speed, attacks per second. */
  speed?: number;
  /** Reach in blocks. */
  reach?: number;
  /** Hunger restored. */
  food?: number;
  /** Saturation restored. */
  saturation?: number;
  /** Potential effect id. */
  effect?: string;
  /** Potential effect duration in seconds. */
  duration?: number;
  /** Effect amplifier tier. */
  amplifier?: number;
  /** Progression tier, 0 = starter. */
  tier?: number;
  /** Icon tint. */
  color?: number;
  /** Crafting recipe as a flat 9-slot grid (0 = empty). */
  recipe?: number[];
  /** Fuels a furnace for this many seconds. */
  fuel?: number;
  /** Sell price at merchants. */
  price?: number;
  description?: string;
}

