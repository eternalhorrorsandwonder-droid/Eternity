export const ITEM_BY_ID: Map<number, ItemDef> = new Map(ITEM_LIST.map((i) => [i.id, i]));

/**
 * The declaration list above is dense, but every gameplay lookup is by id —
 * `ITEMS[stack.id]`, `ITEMS[held.id]`, `ITEMS[itemId]`. Indexing the dense
 * list directly would silently return the wrong item, or undefined. So the
 * exported array is padded out to the highest id here; it is sparse by
 * design and only ever read with an id.
 *
 * Iterate `ITEM_LIST` when you want every item, not `ITEMS`.
 */
const MAX_ITEM_ID = ITEM_LIST.reduce((m, d) => Math.max(m, d.id), 0);
export const ITEMS: (ItemDef | undefined)[] = new Array<ItemDef | undefined>(MAX_ITEM_ID + 1);
for (const def of ITEM_LIST) ITEMS[def.id] = def;
export { ITEM_LIST };

/** Fast lookup with a fallback so a bad id never crashes the game. */
export function item(id: number): ItemDef {
  return ITEM_BY_ID.get(id) ?? MISSING_ITEM;
}

const MISSING_ITEM: ItemDef = { id: 0, name: 'Unknown', kind: 'misc', stack: 1 };

export function itemName(id: number): string {
  return item(id).name;
}

/** Every item id that appears in a recipe's inputs or outputs. */
export function recipeIngredients(id: number): number[] {
  const def = item(id);
  if (!def.recipe) return [];
  return def.recipe.filter((x) => x > 0);
}
