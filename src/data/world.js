export const REGIONS = [...VALE_REGIONS, ...REACHES, ...MERIDIAN, ...SOUND_REGIONS];

export const REGION_BY_ID = Object.fromEntries(
  REGIONS.map((region) => [region.id, region]),
);
export const REGION_BY_GRID = Object.fromEntries(
  REGIONS.map((region) => [`${region.gx},${region.gz}`, region]),
);
export const regionCenter = (region) => ({
  x: (region.gx - 2) * REGION_SIZE,
  z: region.gz * REGION_SIZE,
});
export function regionAt(x, z) {
  const gx = Math.floor(x / REGION_SIZE + 2.5);
  const gz = Math.floor(z / REGION_SIZE + 0.5);
  return REGION_BY_GRID[`${gx},${gz}`] || null;
}
export function worldPosition(region, x, z) {
  const center = regionCenter(region);
  return { x: center.x + x, z: center.z + z };
}
export const worldBounds = {
  minX: -2.5 * REGION_SIZE + 1.2,
  maxX: 2.5 * REGION_SIZE - 1.2,
  minZ: -0.5 * REGION_SIZE + 1.2,
  maxZ: 7.5 * REGION_SIZE - 1.2,
};
